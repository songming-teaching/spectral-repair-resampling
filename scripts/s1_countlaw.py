r"""s1_countlaw.py -- S1: the count-law sanity panel (a recorded design decision, S1 row: "count-law histogram
(data in the library, minutes-level)").

WHAT THIS CHECKS.  Every EXP-1 eigenvalue spectrum is built from a COUNT vector n (the number of
particles that land on each column).  The whole spectral-repair story is conditional on that count
vector following the law the theory assumes, so S1 is the sanity check underneath Fig. 1(a): the
empirical histogram of n, against the closed-form law, for both resampling schemes.

The counts are NOT re-sampled here by a fresh experiment.  They are regenerated by replaying EXP-1's
own seed sequence (config.rng("exp1", N, int(10*alpha), rep)) in the producer's own draw order, so
the histogram is over exactly the counts the published spectra were built from -- a figure that
re-sampled its own data would be showing a different experiment.

Two schemes, two laws:
  multi  : n ~ Multinomial(N, lambda)               -> mixture-of-Poisson(nu) = NegBin(alpha, p)
  res    : n ~ Multinomial(R_N, u) + floor(lambda)  -> mix-Poisson of the residual, shifted

Panels: (a) empirical vs theory pmf, or in the second panel (b) the RANK identity behind the zero
atom --  E[zero atom] = 1 - (N p_s - 1)/d -- is a direct consequence of the count law, so it belongs
on the same page as its cause.

Usage:  python s1_countlaw.py <stage>
"""
import json, os, sys
import numpy as np
import matplotlib
matplotlib.use("Agg")
import matplotlib.pyplot as plt

E = sys.argv[1]
D, F, RS = [os.path.join(E, x) for x in ("data", "figures", "results")]
os.makedirs(F, exist_ok=True)
sys.path.insert(0, os.path.dirname(os.path.dirname(os.path.abspath(__file__))))
from srlab import config, laws, sampling          # noqa: E402
from srlab.laws import trim_pmf                   # noqa: E402

C = config.EXP1["c"]
CASES = [(500, 1.0), (2000, 1.0), (2000, 0.3)]     # (N, alpha); alpha=0.3 is the heavy-tail case

rows = []
for N, al in CASES:
    # REPLAY EXP-1's EXACT DRAW ORDER (srlab/experiments/exp1.py:39-45): gamma_weights, then the
    # d x N standard-normal matrix X, ONLY THEN the two count draws.  Drawing the counts without
    # consuming the X block would advance the generator differently and yield counts that belong to
    # no published spectrum -- the histogram would be of a different experiment wearing the same seed.
    rng = config.rng("exp1", N, int(al * 10), 0)
    d = int(round(C * N)); d0 = int(round(0.7 * d))
    sig = np.where(np.arange(d) < d0, 0.5, 2.5)
    lam = sampling.gamma_weights(rng, al, N)
    _ = np.sqrt(sig)[:, None] * rng.standard_normal((d, N))     # consume X, order-mandatory
    counts = {"multi": sampling.multinomial(rng, lam), "res": sampling.residual(rng, lam)}
    for scheme in ("multi", "res"):
        n = counts[scheme]
        nu = laws.oracle(scheme, al)          # returns the trimmed pmf itself (M34), not a tuple
        rows.append(dict(N=N, alpha=al, scheme=scheme, n=n, nu=nu,
                         r2N=float(np.mean(lam ** 2)), EU_N=float((N - int(np.floor(lam).sum())) / N)))

INK, INK2 = "#0b0b0b", "#52514e"
plt.rcParams.update({"font.size": 8, "figure.dpi": 150, "axes.edgecolor": INK2, "axes.labelcolor": INK,
                     "xtick.color": INK2, "ytick.color": INK2,
                     "axes.spines.top": False, "axes.spines.right": False})
fig, axs = plt.subplots(1, 3, figsize=(11, 3.1))
COLS = {"multi": "#2a78d6", "res": "#eb6834"}

# ---- (a) empirical count pmf vs the mix-Poisson law, N=2000, alpha=1 ----------------------------
ax = axs[0]
case = (2000, 1.0)
for r in [x for x in rows if (x["N"], x["alpha"]) == case]:
    n, nu = r["n"], r["nu"]
    kmax = min(int(nu.shape[0]) - 1, int(n.max()))
    ks = np.arange(kmax + 1)
    emp = np.bincount(np.clip(n, 0, kmax), minlength=kmax + 1)[: kmax + 1] / len(n)
    emp[kmax] += float(np.sum(n > kmax)) / len(n)        # tail collapapsed into the last bar, and said so
    w = 0.38
    ax.bar(ks - w / 2, emp, width=w, color=COLS[r["scheme"]], alpha=0.85, edgecolor="k", lw=0.3,
           label=f"{r['scheme']}: empirical")
    ax.plot(ks + w / 2, nu[: kmax + 1], "s", ms=3.4, color=COLS[r["scheme"]], mfc="none", mew=1,
            label=f"{r['scheme']}: mix-Poisson law")
ax.set_xlabel("particle count $n_j$"); ax.set_ylabel("pmf")
ax.set_title("(a) the count law holds, $N=2000$, $\\alpha=1$", fontsize=8, loc="left")
ax.legend(fontsize=6, frameon=False)

# ---- (b) the same, heavy tail alpha=0.3 ----------------------------------------------------------
ax = axs[1]
case = (2000, 0.3)
for r in [x for x in rows if (x["N"], x["alpha"]) == case]:
    n, nu = r["n"], r["nu"]
    kmax = min(int(nu.shape[0]) - 1, int(n.max()))
    ks = np.arange(kmax + 1)
    emp = np.bincount(np.clip(n, 0, kmax), minlength=kmax + 1)[: kmax + 1] / len(n)
    emp[kmax] += float(np.sum(n > kmax)) / len(n)
    ax.plot(ks, np.maximum(emp, 1e-6), "o", ms=3, color=COLS[r["scheme"]], alpha=0.7,
            label=f"{r['scheme']}: empirical")
    ax.plot(ks, np.maximum(nu[: kmax + 1], 1e-6), "-", lw=1, color=COLS[r["scheme"]],
            label=f"{r['scheme']}: law")
ax.set_yscale("log"); ax.set_xscale("symlog", linthresh=1)
ax.set_xlabel("particle count $n_j$"); ax.set_ylabel("pmf")
ax.set_title("(b) heavy tail $\\alpha=0.3$: law tracks the tail", fontsize=8, loc="left")
ax.legend(fontsize=6, frameon=False)

# ---- (c) the rank identity behind the zero atom --------------------------------------------------
# E[zero atom] = 1 - (N p_s - 1)/d, with p_s the active-fraction of the count law.  The identity is a
# consequence of the count law; reading it here makes the zero atom's origin checkable at a glance.
ax = axs[2]
for scheme in ("multi", "res"):
    for N, al in CASES:
        r = [x for x in rows if (x["N"], x["alpha"]) == (N, al) and x["scheme"] == scheme][0]
        nu, n = r["nu"], r["n"]
        nz = np.nonzero(nu > 1e-15)[0]
        ps = float(nu[nz].sum() / len(nz)) if len(nz) else 0.0   # active fraction of the law
        d = int(round(C * N))
        pred_atom = max(0.0, 1 - (N * ps - 1) / d)
        emp_atom = float(np.mean(n <= 1e-12 * max(n.max(), 1)))   # empirical zero-atom share
        ax.plot(pred_atom, emp_atom, "o", ms=7, color=COLS[scheme],
                mfc="none" if scheme == "res" else COLS[scheme], mew=1.2,
                label=f"{scheme}" if (N, al) == CASES[0] else None)
        ax.annotate(f"$N$={N}\n$\\alpha$={al:g}", (pred_atom, emp_atom), fontsize=5.5,
                    textcoords="offset points", xytext=(5, -3), color=INK2)
lim = [0, 1]
ax.plot(lim, lim, "k--", lw=0.8)
ax.set_xlim(-0.03, 0.75); ax.set_ylim(-0.03, 0.75)
ax.set_xlabel("count-rank prediction $1-(Np_s-1)/d$"); ax.set_ylabel("empirical zero-atom share")
ax.set_title("(c) the synthetic zero atom is bookkeeping", fontsize=8, loc="left")
ax.legend(fontsize=6, frameon=False, loc="lower right")

fig.tight_layout()
fig.savefig(os.path.join(F, "figS1_countlaw.pdf")); fig.savefig(os.path.join(F, "figS1_countlaw.png"))
plt.close(fig)

summary = {}
for r in rows:
    nu, n = r["nu"], r["n"]
    kmax = min(int(nu.shape[0]) - 1, int(n.max()))
    ks = np.arange(kmax + 1)
    emp = np.bincount(np.clip(n, 0, kmax), minlength=kmax + 1)[: kmax + 1] / len(n)
    l1 = float(np.sum(np.abs(emp - nu[: kmax + 1])))
    summary[f"N{r['N']}_a{r['alpha']}_{r['scheme']}"] = dict(
        n_particles=len(n), mean_n=float(n.mean()), var_n=float(n.var()),
        r2N=r["r2N"], EU_N=r["EU_N"], l1_emp_vs_law=l1, kmax_used=kmax,
        tail_collapsed_fraction=float(np.mean(n > kmax)))
json.dump(dict(cases=[dict(N=N, alpha=al) for N, al in CASES], per_case=summary,
               note=("Counts replayed from EXP-1's own seed sequence, not re-sampled: the histogram "
                     "is over the counts the published spectra were built from.  The far tail is "
                     "collapsed into the last plotted bar; its fraction is recorded per case.")),
          open(os.path.join(RS, "s1_countlaw_summary.json"), "w"), indent=1)

print("=== S1 count law ===")
for k, v in summary.items():
    print(f"  {k:22s} mean n={v['mean_n']:8.2f}  L1(emp,law)={v['l1_emp_vs_law']:.4f}  "
          f"tail collapsed {v['tail_collapsed_fraction']:.2%}")
