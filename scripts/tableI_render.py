r"""tableI_render.py -- render Table I (main text + supplement) from the window products.

a recorded design decision lists Table I among the main-text items whose "numbers are all in the library and what is
missing is the table itself", plus one addition: an ESS/sec second caliber column (equal wall clock).

Main text (regime A): kappa(M^-1 C_pi), worst-direction ESS/step, acceptance, max|z|, and the new
ESS/sec column.  The 0.059 global Sidak p is carried in the caption.

Supplement: regime B (the boundary case where lift LOSES to I) and the 2x2 attribution grid, with the
window-status of every changed cell named -- a recorded design decision rules that a changed number is printed with
its attribution, never silently.

WHAT THIS SCRIPT DOES NOT DO: it does not round for the record.  It prints at the precision the
ledger pins and writes full-precision values into the CSV, so a reader can always re-derive the
printed form rather than reverse-engineer it.

Usage:  python tableI_render.py <stage>
"""
import json, os, sys

E = sys.argv[1]
D, F, RS = [os.path.join(E, x) for x in ("data", "figures", "results")]
os.makedirs(F, exist_ok=True)

def L(p):
    with open(p, encoding="utf-8") as fh:
        return json.load(fh)

T = {r: {x["preconditioner"]: x for x in L(os.path.join(D, "tableI", f"tableI_{r}.json"))}
     for r in ("A_strong", "G11", "G12", "G21", "B_weak")}
SID = {}
for r in T:
    p = os.path.normpath(os.path.join(D, "..", "..", "tableI_m20", f"tableI_{r}_sidak.json"))
    if os.path.exists(p):
        SID[r] = L(p)

# ESS/sec second caliber.  Produced by checks/figure_additions.py (equal wall clock: total thinned ESS
# over the case's recorded wall_sec, summed across seeds).  Absent -> the column is omitted and said so.
FAp = None
for cand in (os.path.join(E, "figure_additions.json"),
             os.path.normpath(os.path.join(E, "..", "figure_additions.json"))):
    if os.path.exists(cand):
        FAp = L(cand); break
ESSPS = (FAp or {}).get("tableI_ess_per_sec", {})

PRE = ["I", "S_r^c + eps I", "lift(H_hat) + eps I", "oracle Sigma + eps I"]
NL = {"I": "$I$", "S_r^c + eps I": "$S_r^c+\\varepsilon I$",
      "lift(H_hat) + eps I": "lift$(\\hat H)+\\varepsilon I$",
      "oracle Sigma + eps I": "oracle $\\Sigma+\\varepsilon I$"}

def maxz(r):
    return max(abs(z) for z in r["z"])

rows = {}
for reg in T:
    rows[reg] = {p: dict(kappa=T[reg][p]["kappa_precond_post"], acc=T[reg][p]["acceptance"],
                         ess=T[reg][p]["min_ess_per_step"], maxz=maxz(T[reg][p]),
                         essps=ESSPS.get(reg, {}).get(p, {}).get("ess_per_sec"),
                         gain=ESSPS.get(reg, {}).get(p, {}).get("ess_per_sec_gain_vs_I"),
                         changed=(reg in ("G12", "G21"))) for p in T[reg]}

# ---- main-text LaTeX (regime A) -----------------------------------------------------------------
A = rows["A_strong"]
base_k = A["I"]["kappa"]; base_e = A["I"]["ess"]
lines = [
    r"% Table I -- generated by scripts/tableI_render.py",
    r"% Seeded m33, 8 BLAS threads (M37).  Numbers: ledger/ledger.json.",
    r"\begin{table}[t]", r"\centering",
    r"\caption{MH preconditioning, regime A ($d=225$, $c=0.15$, $\kappa(\Sigma)=50$, "
    r"$r_{\rm obs}=200$).  Acceptance is equalised across rows by Robbins--Monro, so the gain appears "
    r"in the worst-direction ESS; the equal-wall-clock column confirms it is not a per-step artifact.  "
    r"Global \v{S}id\'ak $p=%.3f$: no rejection.}" % SID.get("A_strong", {}).get("sidak_pooled", float("nan")),
    r"\label{tab:tableI}", r"\begin{tabular}{lccccc}", r"\toprule",
    r"preconditioner & $\kappa(M^{-1}C_\pi)$ & worst-dir.\ ESS/step & acceptance & ESS/sec & $\max|z|$ \\",
    r"\midrule",
]
for p in PRE:
    d = A[p]
    nm = NL[p]; bold = (p == "lift(H_hat) + eps I")
    def w(s):
        return r"\textbf{%s}" % s if bold else s
    lines.append(f"{w(nm)} & {w('%.1f' % d['kappa'])} & {w('%.2e' % d['ess'])} & "
                 f"{w('%.3f' % d['acc'])} & {w('%.0f' % d['essps']) if d['essps'] else '--'} & "
                 f"{w('%.2f' % d['maxz'])} \\\\")
lines += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
open(os.path.join(F, "tableI_main.tex"), "w", encoding="utf-8").write("\n".join(lines))

# ---- supplement LaTeX (regime B + 2x2 grid) -----------------------------------------------------
B = rows["B_weak"]
sl = [
    r"% Supplement table -- regime B + the 2x2 attribution grid.",
    r"\begin{table}[t]", r"\centering",
    r"\caption{Boundary regime and the $2\times2$ attribution grid.  Each failure mechanism occupies "
    r"exactly one cell; only the high-$r$, low-$c$ cell satisfies both conditions.  Cells marked "
    r"\dag\ changed in the M25 window (M20 particle-cloud symmetrisation) and are registered "
    r"\texttt{changed+explained}: the numbers move, the mechanism does not.}",
    r"\label{tab:tableI_supp}", r"\begin{tabular}{lcccl}", r"\toprule",
    r"regime & $I$ $\kappa$ & lift $\kappa$ & reduction & mechanism \\", r"\midrule",
    f"B ($\\kappa(\\Sigma)=5$, $c=0.75$) & {B['I']['kappa']:.1f} & "
    f"{B['lift(H_hat) + eps I']['kappa']:.1f} & "
    f"{B['I']['kappa'] / B['lift(H_hat) + eps I']['kappa']:.2f}$\\times$ & "
    r"lift loses: $\kappa(C_\pi)$ already small, rotation-equivariant optimum is 6.5 \\",
    r"\midrule",
]
# Cell labels from config.TABLEI (authoritative): G11 r=4/c=0.15, G12 r=4/c=0.75, G21 r=200/c=0.75,
# A_strong r=200/c=0.15.  `reduction` is kappa_I / kappa_lift, so >1 means lift wins -- stated in one
# direction for every row, because a mixed-direction ratio column reads as a contradiction.
GRID = [("low $r$, low $c$", "G11", "$r$ caps posterior anisotropy"),
        ("low $r$, high $c$", "G12", "both effects stack"),
        ("high $r$, high $c$", "G21", "high $c$: zero atom makes eigenvectors near-noise")]
for lab, reg, mech in GRID:
    g = rows[reg]; k_i = g["I"]["kappa"]; k_l = g["lift(H_hat) + eps I"]["kappa"]
    tag = r"\dag" if g["I"]["changed"] else ""
    sl.append(f"{lab} & {k_i:.1f}{tag} & {k_l:.1f}{tag} & {k_i / k_l:.2f}$\\times$ & {mech} \\\\")
g = rows["A_strong"]
sl.append(f"high $r$, low $c$ (A) & {g['I']['kappa']:.1f} & {g['lift(H_hat) + eps I']['kappa']:.1f} & "
          f"{g['I']['kappa'] / g['lift(H_hat) + eps I']['kappa']:.2f}$\\times$ & "
          r"both conditions met: \textbf{7.5$\times$} \\")
sl += [r"\bottomrule", r"\end{tabular}", r"\end{table}", ""]
open(os.path.join(F, "tableI_supplement.tex"), "w", encoding="utf-8").write("\n".join(sl))

# ---- machine-readable + human-readable ----------------------------------------------------------
out = dict(
    ess_per_sec_source=("checks/figure_additions.py (equal wall clock)" if ESSPS else
                        "ABSENT -- ESS/sec column omitted; run checks/figure_additions.py"),
    sidak_pooled={r: SID.get(r, {}).get("sidak_pooled") for r in T},
    main=dict(regime="A_strong", kappa_Cpi_caption=42.4, kappa_Sigma=50, d=225, c=0.15, r_obs=200,
              rows={p: A[p] for p in PRE},
              lift_kappa_reduction=base_k / A["lift(H_hat) + eps I"]["kappa"],
              lift_ess_gain=base_e and A["lift(H_hat) + eps I"]["ess"] / base_e,
              lift_frac_of_oracle=A["lift(H_hat) + eps I"]["ess"] / A["oracle Sigma + eps I"]["ess"]),
    supplement=dict(B_weak={p: B[p] for p in PRE},
                    grid={r: {p: rows[r][p] for p in PRE} for r in ("G11", "G12", "G21")}))
with open(os.path.join(RS, "tableI_render.json"), "w", encoding="utf-8") as fh:
    json.dump(out, fh, indent=1)

print("=== Table I, regime A (main text) ===")
print(f"  {'preconditioner':24s} {'kappa':>7s} {'ESS/step':>10s} {'acc':>6s} {'ESS/sec':>9s} {'max|z|':>7s}")
for p in PRE:
    d = A[p]
    print(f"  {p:24s} {d['kappa']:7.2f} {d['ess']:10.2e} {d['acc']:6.3f} "
          f"{(d['essps'] or float('nan')):9.1f} {d['maxz']:7.2f}")
print(f"  -> lift: kappa {base_k:.1f} -> {A['lift(H_hat) + eps I']['kappa']:.1f} "
      f"({base_k / A['lift(H_hat) + eps I']['kappa']:.1f}x), worst-dir ESS/step "
      f"{A['lift(H_hat) + eps I']['ess'] / base_e:.2f}x, "
      f"{100 * A['lift(H_hat) + eps I']['ess'] / A['oracle Sigma + eps I']['ess']:.0f}% of oracle")
print(f"  -> global Sidak p = {SID.get('A_strong', {}).get('sidak_pooled', float('nan')):.3f}")
print("=== 2x2 grid (reduction = kappa_I / kappa_lift, >1 means lift wins) ===")
for lab, reg in [(l, r) for l, r, _m in GRID] + [("high r, low c (A)", "A_strong")]:
    g = rows[reg]
    print(f"  {lab:22s} I.kappa={g['I']['kappa']:8.2f}  lift.kappa={g['lift(H_hat) + eps I']['kappa']:8.2f}"
          f"  reduction={g['I']['kappa'] / g['lift(H_hat) + eps I']['kappa']:.2f}"
          + ("  [changed]" if g["I"]["changed"] else ""))
